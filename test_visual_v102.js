'use strict';
const fs = require('node:fs');
const assert = require('node:assert/strict');
const html = fs.readFileSync('public/index.html', 'utf8');
const css = fs.readFileSync('public/style.css', 'utf8');
const three = fs.readFileSync('public/arena3d.js', 'utf8');
const client = fs.readFileSync('public/client.js', 'utf8');
const frameEnd = html.indexOf('      </div>\n      <div class="touch-controller"');
assert(frameEnd > 0, 'Touch buttons must follow stage-frame, not overlay the 3D arena');
assert(html.indexOf('id="touchController"') > html.indexOf('id="stageFrame"'));
assert(!html.slice(html.indexOf('id="stageFrame"'),frameEnd).includes('id="touchController"'));
assert(css.includes('.stage-col > .touch-controller.active'), 'Mobile control dock style missing');
assert(css.includes('safe-area-inset-bottom'), 'Safe area for mobile toolbar missing');
assert(client.includes("touchController?.classList.toggle('active'"), 'Game state must drive dock visibility');
assert(three.includes('THREE.PointsMaterial') && three.includes('THREE.AdditiveBlending'));
assert(three.includes('mobile?24:46'), 'VFX mobile particle budget missing');
assert(!three.includes('new THREE.OctahedronGeometry(.045+Math.random()'), 'Old one-mesh-per-spark implementation persists');
assert(three.includes('glowTexture') && three.includes('userData.cyclone'));
